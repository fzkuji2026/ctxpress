"""Benchmarks whose official Harbor adapters generate the tasks; run on the shared Harbor task format.

Generate the tasks with the publisher's Harbor adapter (for example `uv run multi-swe-bench --output-dir ...` in
harbor/adapters/multi-swe-bench) and add a dataset_manifest.json declaring the dataset and its release; the official
verifier in each task's tests/ grades it. No conversion happens here, so task IDs, prompts, images and graders stay
the publisher's.
"""
from ctxpress.benchmarks.harbor.tasks import HarborTasks


class OfficialHarbor(HarborTasks):
    REQUIRE_MANIFEST = True
    ADAPTER = ''

    def describe(self):
        return dict(super().describe(), suite='tasks generated by the official Harbor adapter ' + self.ADAPTER,
                    task_scope='Harbor task format from the official adapter; dataset release must be declared',
                    required_resources=['tasks generated by harbor/adapters/' + self.ADAPTER, 'dataset_manifest.json',
                                        'the images the tasks name', 'Codex binary', 'official Harbor runtime'])


class MultiSWEBench(OfficialHarbor):
    NAME = 'multi-swe-bench'
    TITLE = 'Multi-SWE-bench'
    ADAPTER = 'multi-swe-bench'


class SWEBenchMultilingual(OfficialHarbor):
    NAME = 'swe-bench-multilingual'
    TITLE = 'SWE-bench Multilingual'
    ADAPTER = 'swebench_multilingual'


class AppWorld(OfficialHarbor):
    """Tasks from the official Terminal-Bench AppWorld adapter, moved to Harbor with `harbor tasks migrate`."""
    NAME = 'appworld'
    TITLE = 'AppWorld'
    ADAPTER = 'terminal-bench/adapters/appworld, then `harbor tasks migrate`'


class Converted(OfficialHarbor):
    """Official releases packaged as Harbor tasks by ctxpress.benchmarks.convert; items and graders unchanged."""
    def describe(self):
        return dict(super().describe(), suite='official release converted by ' + self.ADAPTER,
                    required_resources=['official release on disk', 'tasks written by ' + self.ADAPTER,
                                        'the prepared image named at conversion', 'Codex binary', 'official Harbor runtime'])


class KernelBench(Converted):
    NAME = 'kernelbench'
    TITLE = 'KernelBench'
    ADAPTER = 'python -m ctxpress.benchmarks.convert kernelbench (official eval_kernel_against_ref; NVIDIA GPU)'


class LongBenchV2(Converted):
    NAME = 'longbench-v2'
    TITLE = 'LongBench v2'
    ADAPTER = 'python -m ctxpress.benchmarks.convert longbench-v2 (context as a file; official letter match)'


class SWEQA(Converted):
    NAME = 'swe-qa'
    TITLE = 'SWE-QA'
    ADAPTER = 'python -m ctxpress.benchmarks.convert swe-qa (answers collected for the official LLM judge)'
